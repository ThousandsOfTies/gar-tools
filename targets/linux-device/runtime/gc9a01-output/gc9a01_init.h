typedef int (*gar_lcd_command)(void *context, uint8_t command, const uint8_t *data, size_t length);
typedef void (*gar_lcd_delay)(void *context, unsigned milliseconds);

/* Reset the controller before calling this. Sends RGB565, MX/BGR orientation,
 * inversion, sleep-out and display-on. No Product pixels or application state. */
static inline int gar_gc9a01_initialize(void *context, gar_lcd_command command, gar_lcd_delay delay) {
    static const uint8_t sequence[] = {
        0xef,0, 0xeb,1,0x14, 0xfe,0, 0xef,0, 0xeb,1,0x14,
        0x84,1,0x40, 0x85,1,0xff, 0x86,1,0xff, 0x87,1,0xff,
        0x88,1,0x0a, 0x89,1,0x21, 0x8a,1,0x00, 0x8b,1,0x80,
        0x8c,1,0x01, 0x8d,1,0x01, 0x8e,1,0xff, 0x8f,1,0xff,
        0xb6,2,0x00,0x00, 0x36,1,0x48, 0x3a,1,0x05,
        0x90,4,0x08,0x08,0x08,0x08, 0xbd,1,0x06, 0xbc,1,0x00,
        0xff,3,0x60,0x01,0x04, 0xc3,1,0x13, 0xc4,1,0x13,
        0xc9,1,0x22, 0xbe,1,0x11, 0xe1,2,0x10,0x0e,
        0xdf,3,0x21,0x0c,0x02,
        0xf0,6,0x45,0x09,0x08,0x08,0x26,0x2a,
        0xf1,6,0x43,0x70,0x72,0x36,0x37,0x6f,
        0xf2,6,0x45,0x09,0x08,0x08,0x26,0x2a,
        0xf3,6,0x43,0x70,0x72,0x36,0x37,0x6f,
        0xed,2,0x1b,0x0b, 0xae,1,0x77, 0xcd,1,0x63, 0xe8,1,0x34,
        0x62,12,0x18,0x0d,0x71,0xed,0x70,0x70,0x18,0x0f,0x71,0xef,0x70,0x70,
        0x63,12,0x18,0x11,0x71,0xf1,0x70,0x70,0x18,0x13,0x71,0xf3,0x70,0x70,
        0x64,7,0x28,0x29,0xf1,0x01,0xf1,0x00,0x07,
        0x66,10,0x3c,0x00,0xcd,0x67,0x45,0x45,0x10,0x00,0x00,0x00,
        0x67,10,0x00,0x3c,0x00,0x00,0x00,0x01,0x54,0x10,0x32,0x98,
        0x74,7,0x10,0x85,0x80,0x00,0x00,0x4e,0x00, 0x98,2,0x3e,0x07,
        0x35,0, 0x21,0, 0x11,0x80, 0x29,0x80, 0x00
    };
    const uint8_t *cursor = sequence;
    while (*cursor) {
        uint8_t instruction = *cursor++, count = *cursor++;
        size_t length = count & 0x7f;
        if (command(context, instruction, cursor, length) != 0) return -1;
        cursor += length;
        if (count & 0x80) delay(context, 150);
    }
    return 0;
}
